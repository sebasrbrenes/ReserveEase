// Country code + local number -> E.164 ("+50688887777"), or null when empty.
export const toE164 = (countryCode, localNumber) => {
  const digits = String(localNumber || '').replace(/[^0-9]/g, '');
  return digits ? `${countryCode}${digits}` : null;
};
